def parse_single_edi_file(file_path):
    """
    Membaca satu file data MT berformat EDI dan mengubahnya menjadi DataFrame Pandas.
    Juga mengekstrak metadata penting.
    """
    try:
        with open(file_path, 'r', errors='ignore') as f:
            content = f.read()
    except FileNotFoundError:
        print(f"-> ERROR: File tidak ditemukan di '{file_path}'")
        return None, None

    metadata = {}
    elev_match = re.search(r'ELEV=(-?\d+\.?\d*)', content, re.IGNORECASE)
    metadata['elevation'] = float(elev_match.group(1)) if elev_match else 0.0

    column_names = [
        "FREQ", "ZROT", "ZXXR", "ZXXI", "ZXX.VAR", "ZXYR", "ZXYI", "ZXY.VAR",
        "ZYXR", "ZYXI", "ZYX.VAR", "ZYYR", "ZYYI", "ZYY.VAR", "TROT",
        "TXR.EXP", "TXI.EXP", "TXVAR.EXP", "TYR.EXP", "TYI.EXP", "TYVAR.EXP"
    ]
    data_dict = {name: [] for name in column_names}

    nfreq_match = re.search(r'>=MTSECT\s*NFREQ=(\d+)', content, re.IGNORECASE)
    if not nfreq_match:
        print(f"-> ERROR: Tidak dapat menemukan 'NFREQ' di file '{file_path}'.")
        return None, None
    num_freqs = int(nfreq_match.group(1))

    blocks = content.split('>')
    for block in blocks:
        block = block.strip()
        if not block: continue

        current_key = None
        for key in column_names:
            if re.match(r'^{}\b'.format(re.escape(key)), block):
                current_key = key
                break

        if current_key:
            lines = block.splitlines()[1:]
            all_numbers_str = ' '.join(lines)
            numbers = [float(num) for num in all_numbers_str.split()]
            data_dict[current_key].extend(numbers)

    try:
        for key in column_names:
            if len(data_dict[key]) == 0: data_dict[key] = [0.0] * num_freqs
            elif len(data_dict[key]) != num_freqs:
                 print(f"-> WARNING: Data tidak konsisten di '{key}' pada file '{file_path}'.")

        df = pd.DataFrame(data_dict)
        return df, metadata
    except ValueError as e:
        print(f"-> ERROR: Gagal membuat DataFrame dari '{file_path}': {e}")
        return None, None

def calculate_zssq_complex(dataframe):
    """
    Menghitung komponen Real dan Imajiner dari Sum of Squares Impedance (Zssq)
    dan menambahkannya ke DataFrame.
    """
    if dataframe is None: return None

    Zxx_R2_minus_I2 = dataframe['ZXXR']**2 - dataframe['ZXXI']**2
    Zxx_2RI = 2 * dataframe['ZXXR'] * dataframe['ZXXI']
    Zxy_R2_minus_I2 = dataframe['ZXYR']**2 - dataframe['ZXYI']**2
    Zxy_2RI = 2 * dataframe['ZXYR'] * dataframe['ZXYI']
    Zyx_R2_minus_I2 = dataframe['ZYXR']**2 - dataframe['ZYXI']**2
    Zyx_2RI = 2 * dataframe['ZYXR'] * dataframe['ZYXI']
    Zyy_R2_minus_I2 = dataframe['ZYYR']**2 - dataframe['ZYYI']**2
    Zyy_2RI = 2 * dataframe['ZYYR'] * dataframe['ZYYI']

    W_R_numerator = Zxx_R2_minus_I2 + Zxy_R2_minus_I2 + Zyx_R2_minus_I2 + Zyy_R2_minus_I2
    W_I_numerator = Zxx_2RI + Zxy_2RI + Zyx_2RI + Zyy_2RI

    W_R = W_R_numerator / 2
    W_I = W_I_numerator / 2

    W_mag = np.sqrt(W_R**2 + W_I**2)
    W_I_sgn = np.sign(W_I)
    W_I_sgn[W_I_sgn == 0] = 1

    dataframe['ZssqR'] = np.sqrt((W_mag + W_R) / 2)
    dataframe['ZssqI'] = W_I_sgn * np.sqrt((W_mag - W_R) / 2)

    return dataframe

def calculate_resistivity_and_phase(dataframe):
    """
    Menghitung resistivitas semu dan fase dari data impedansi.
    """
    if dataframe is None: return None

    results_df = pd.DataFrame()
    results_df['Freq(Hz)'] = dataframe['FREQ']
    results_df['Period(s)'] = 1 / dataframe['FREQ']

    components = ['ZXX', 'ZXY', 'ZYX', 'ZYY']
    if 'ZssqR' in dataframe.columns and 'ZssqI' in dataframe.columns:
        components.append('Zssq')

    for comp in components:
        real_col, imag_col = f'{comp}R', f'{comp}I'
        abs_z_sq = dataframe[real_col]**2 + dataframe[imag_col]**2
        results_df[f'Rho_App_{comp}'] = 0.2 * results_df['Period(s)'] * abs_z_sq
        phase_rad = np.arctan2(dataframe[imag_col], dataframe[real_col])
        results_df[f'Phase_{comp}(deg)'] = np.degrees(phase_rad)

    return results_df

def read_site_list(site_file_path):
    """
    Membaca daftar nama file EDI dari file teks berformat tabel spasi.
    Format yang diharapkan: [NamaSitus] [Lat] [Lon] [Elev]
    """
    edi_files = []
    
    try:
        with open(site_file_path, 'r', errors='ignore') as f:
            lines = f.readlines()
            
        for line in lines:
            line = line.strip()
            if not line:
                continue  # Abaikan jika ada baris kosong
            
            # Memecah baris berdasarkan spasi
            parts = line.split()
            
            # Memastikan baris memiliki data (minimal nama situs)
            if parts:
                site_name = parts[0]
                
                # Menambahkan akhiran .edi karena di dalam file mentah tidak ada
                if not site_name.lower().endswith('.edi'):
                    site_name += '.edi'
                    
                edi_files.append(site_name)
        
        # Karena di dalam file Sitelist Anda tidak ada baris header "Number of site",
        # kita otomatis menghitung jumlah total baris yang berhasil diekstrak.
        declared_count = len(edi_files)
        
        # Mengembalikan 2 nilai (Tuple) sesuai dengan yang diminta oleh Notebook Anda
        return declared_count, edi_files
        
    except FileNotFoundError:
        print(f"-> ERROR: File daftar situs '{site_file_path}' tidak ditemukan.")
        return None

