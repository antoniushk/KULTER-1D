def write_edi_with_inserted_zssq(dataframe, original_file_path, output_file_path):
    """
    Menulis DataFrame kembali ke format file EDI, dengan menyisipkan ZssqR dan ZssqI
    setelah ZROT.
    """
    header_content = []
    try:
        with open(original_file_path, 'r', errors='ignore') as f:
            for line in f:
                if line.strip().startswith('>!****FREQUENCIES****!'):
                    break
                header_content.append(line)
    except Exception as e:
        print(f"-> ERROR: Gagal membaca header dari '{original_file_path}': {e}")
        return

    with open(output_file_path, 'w') as f:
        f.writelines(header_content)

        def format_and_write_block(series, block_header, block_name_comment):
            if block_header: f.write(f"{block_header}\n")
            f.write(f">{block_name_comment}\n")
            values = series.tolist()
            for i in range(0, len(values), 6):
                chunk = values[i:i+6]
                line = "   ".join([f"{v:14.6e}" for v in chunk])
                f.write(f"   {line}\n")

        num_freqs = len(dataframe)

        # Urutan penulisan blok data yang baru
        block_order = {
            "FREQ": ('>!****FREQUENCIES****!', f'FREQ // {num_freqs}'),
            "ZROT": ('>!****IMPEDANCE ROTATION ANGLES****!', f'ZROT // {num_freqs}'),
            "ZssqR": ('>!****SUM OF SQUARES IMPEDANCE (COMPLEX)****!', f'ZSSQR // {num_freqs}'),
            "ZssqI": ('', f'ZSSQI // {num_freqs}'),
            "ZXXR": ('>!****IMPEDANCES****!', f'ZXXR ROT=ZROT // {num_freqs}'), "ZXXI": ('', f'ZXXI ROT=ZROT // {num_freqs}'), "ZXX.VAR": ('', f'ZXX.VAR ROT=ZROT // {num_freqs}'),
            "ZXYR": ('', f'ZXYR ROT=ZROT // {num_freqs}'), "ZXYI": ('', f'ZXYI ROT=ZROT // {num_freqs}'), "ZXY.VAR": ('', f'ZXY.VAR ROT=ZROT // {num_freqs}'),
            "ZYXR": ('', f'ZYXR ROT=ZROT // {num_freqs}'), "ZYXI": ('', f'ZYXI ROT=ZROT // {num_freqs}'), "ZYX.VAR": ('', f'ZYX.VAR ROT=ZROT // {num_freqs}'),
            "ZYYR": ('', f'ZYYR ROT=ZROT // {num_freqs}'), "ZYYI": ('', f'ZYYI ROT=ZROT // {num_freqs}'), "ZYY.VAR": ('', f'ZYY.VAR ROT=ZROT // {num_freqs}'),
            "TROT": ('>!****TIPPER ROTATION ANGLES****!', f'TROT // {num_freqs}'),
            "TXR.EXP": ('>!****TIPPER****!', f'TXR.EXP ROT=TROT // {num_freqs}'), "TXI.EXP": ('', f'TXI.EXP ROT=TROT // {num_freqs}'), "TXVAR.EXP": ('', f'TXVAR.EXP ROT=TROT // {num_freqs}'),
            "TYR.EXP": ('', f'TYR.EXP ROT=TROT // {num_freqs}'), "TYI.EXP": ('', f'TYI.EXP ROT=TROT // {num_freqs}'), "TYVAR.EXP": ('', f'TYVAR.EXP ROT=TROT // {num_freqs}'),
        }

        for col_name, (header, comment) in block_order.items():
            if col_name in dataframe.columns:
                format_and_write_block(dataframe[col_name], header, comment)

        f.write(">END\n")